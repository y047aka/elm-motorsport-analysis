#!/usr/bin/env node
/**
 * Writes the served geometry bytes, and the circuit maps served beside them, out as the Elm modules the package's tests read, so those tests check the files the app ships rather than a copy kept by hand beside them.
 * A circuit joins the tests by its file alone.
 *
 * The flake's `generateElm` runs this, after `syncCircuitData` has put the pinned bytes under `app/static/`.
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const helpers = join(root, "package/tests/Motorsport/TestHelpers");

const sources = [
  { dir: "app/static/geometry", extension: ".geojson", helper: "Survey" },
  { dir: "app/static/circuit-maps", extension: ".json", helper: "Map" },
];

const pascalCase = (word) =>
  word
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const circuitWords = (dir, extension) => {
  const words = readdirSync(join(root, dir))
    .filter((name) => name.endsWith(extension))
    .map((name) => name.slice(0, -extension.length))
    .sort();
  if (words.length === 0) {
    throw new Error(`${dir} holds no ${extension} file, so no test module has a circuit name to be written under`);
  }
  return words;
};

let written = 0;

for (const { dir, extension, helper } of sources) {
  for (const word of circuitWords(dir, extension)) {
    const module = `${helper}.${pascalCase(word)}`;
    const file = join(dir, `${word}${extension}`);
    const text = readFileSync(join(root, file), "utf8");
    const path = join(helpers, `${module.replaceAll(".", "/")}.elm`);

    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(
      path,
      `module Motorsport.TestHelpers.${module} exposing (text)

{-| Generated by \`app/codegen/test-fixtures.mjs\` from
\`${file}\`: the bytes the app ships, so the package's
tests read those and not a copy kept by hand. Do not edit; the flake's
\`generateElm\` writes it again from the file.
-}


text : String
text =
    ${JSON.stringify(text)}
`,
    );

    written += 1;
    console.log(`${module}: ${text.length} bytes of ${file} written as a test module`);
  }
}

console.log(`${written} test modules written from ${sources.map((s) => s.dir).join(" and ")}`);
