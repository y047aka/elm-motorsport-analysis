#!/usr/bin/env node
/**
 * Writes the served geometry bytes, and the circuit maps served beside them, out
 * as the Elm modules the package's tests read, so those tests check the files
 * the app ships rather than a copy kept by hand beside them.
 *
 * `nix run .#test` runs this before the package's tests. The modules are
 * generated and ignored; a bare `elm-test` without them fails to compile by
 * module name.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const helpers = join(root, "package/tests/Motorsport/TestHelpers");

const fixtures = [
  { module: "Survey.Barcelona", file: "app/static/geometry/barcelona.geojson" },
  { module: "Survey.Cota", file: "app/static/geometry/cota.geojson" },
  { module: "Survey.Fuji", file: "app/static/geometry/fuji.geojson" },
  { module: "Survey.LeMans", file: "app/static/geometry/le_mans.geojson" },
  { module: "Survey.Monza", file: "app/static/geometry/monza.geojson" },
  { module: "Survey.Spa", file: "app/static/geometry/spa.geojson" },
  { module: "Map.Barcelona", file: "app/static/circuit-maps/barcelona.json" },
  { module: "Map.Cota", file: "app/static/circuit-maps/cota.json" },
  { module: "Map.Fuji", file: "app/static/circuit-maps/fuji.json" },
  { module: "Map.LeMans", file: "app/static/circuit-maps/le_mans.json" },
  { module: "Map.Monza", file: "app/static/circuit-maps/monza.json" },
  { module: "Map.Spa", file: "app/static/circuit-maps/spa.json" },
];

for (const { module, file } of fixtures) {
  const text = readFileSync(join(root, file), "utf8");

  // A block string carries the bytes as they are only if nothing in them
  // means anything to Elm.
  if (text.includes('"""')) throw new Error(`${file} holds """, which no block string can hold`);
  if (text.includes("\\")) throw new Error(`${file} holds a backslash, which a block string would pass on escaped`);

  const path = join(helpers, `${module.replaceAll(".", "/")}.elm`);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(
    path,
    `module Motorsport.TestHelpers.${module} exposing (text)

{-| Generated by \`app/scripts/test-fixtures.mjs\` from
\`${file}\`: the bytes the app ships, so the package's
tests read those and not a copy kept by hand. Do not edit; \`nix run .#test\`
writes it again from the file.
-}


text : String
text =
    """${text}"""
`,
  );

  console.log(`${module}: ${text.length} bytes of ${file} written as a test module`);
}
