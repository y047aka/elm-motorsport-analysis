#!/usr/bin/env node
/**
 * Writes the served geometry bytes out as the Elm modules the package's tests
 * read, so those tests check the geometry the app ships rather than a copy
 * kept by hand beside it.
 *
 * `nix run .#test` runs this before the package's tests. The modules are
 * generated and ignored; a bare `elm-test` without them fails to compile by
 * module name.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../package/tests/Motorsport/TestHelpers/Survey");

const fixtures = [
  { module: "Cota", file: "cota.geojson" },
  { module: "LeMans", file: "le_mans.geojson" },
];

mkdirSync(out, { recursive: true });

for (const { module, file } of fixtures) {
  const text = readFileSync(join(here, "../static/geometry", file), "utf8");

  // A block string carries the bytes as they are only if nothing in them
  // means anything to Elm.
  if (text.includes('"""')) throw new Error(`${file} holds """, which no block string can hold`);
  if (text.includes("\\")) throw new Error(`${file} holds a backslash, which a block string would pass on escaped`);

  writeFileSync(
    join(out, `${module}.elm`),
    `module Motorsport.TestHelpers.Survey.${module} exposing (text)

{-| Generated by \`app/scripts/test-fixtures.mjs\` from
\`app/static/geometry/${file}\`: the bytes the app serves, so the package's
tests read those and not a copy kept by hand. Do not edit; \`nix run .#test\`
writes it again from the file.
-}


text : String
text =
    """${text}"""
`,
  );

  console.log(`${module}: ${text.length} bytes of ${file} written as a test module`);
}
